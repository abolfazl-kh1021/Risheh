export function MSymbol({
  name,
  className,
  filled = false,
  size,
}: {
  name: string;
  className?: string;
  filled?: boolean;
  size?: number;
}) {
  const cp = ICON_CODEPOINTS[name];
  return (
    <span
      aria-hidden="true"
      className={cn("material-symbols-outlined", filled && "filled", className)}
      style={size ? { fontSize: size } : undefined}
    >
      {cp === undefined ? name : String.fromCodePoint(cp)}
    </span>
  );
}